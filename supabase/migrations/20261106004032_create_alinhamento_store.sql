-- Private persistence for the single-operator MVP. JSONB remains authoritative:
-- unknown payload fields are preserved, while invoker views make audits easier.
-- This schema is deliberately not exposed through the public Data API.
CREATE SCHEMA alinhamento;
REVOKE ALL ON SCHEMA alinhamento FROM PUBLIC, anon, authenticated;

CREATE TABLE alinhamento.batches (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    request_id uuid NOT NULL UNIQUE,
    body jsonb NOT NULL CHECK (jsonb_typeof(body) = 'object'),
    revision bigint NOT NULL DEFAULT 0 CHECK (revision >= 0),
    request_body_hash text NOT NULL CHECK (request_body_hash ~ '^[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT batch_body_id_matches CHECK (body ? 'id' AND body->'id' = to_jsonb(id))
);

CREATE TABLE alinhamento.dictionary_edits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    request_id uuid NOT NULL UNIQUE,
    body jsonb NOT NULL CHECK (jsonb_typeof(body) = 'object'),
    request_body_hash text NOT NULL CHECK (request_body_hash ~ '^[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- A source row is mapped once. Its original JSON and fingerprint remain an
-- immutable audit copy even if the active batch is later reviewed or annotated.
CREATE TABLE alinhamento.sqlite_imports (
    source_key text NOT NULL CHECK (length(source_key) BETWEEN 1 AND 2048),
    entity_type text NOT NULL CHECK (entity_type IN ('batch', 'dictionary_edit')),
    source_id bigint NOT NULL CHECK (source_id > 0),
    fingerprint text NOT NULL CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
    original_body jsonb NOT NULL CHECK (jsonb_typeof(original_body) = 'object'),
    batch_id bigint REFERENCES alinhamento.batches(id),
    dictionary_edit_id bigint REFERENCES alinhamento.dictionary_edits(id),
    remote_id bigint GENERATED ALWAYS AS (coalesce(batch_id, dictionary_edit_id)) STORED,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (source_key, entity_type, source_id),
    CONSTRAINT import_target_matches_type CHECK (
        (entity_type = 'batch' AND batch_id IS NOT NULL AND dictionary_edit_id IS NULL)
        OR (entity_type = 'dictionary_edit' AND dictionary_edit_id IS NOT NULL AND batch_id IS NULL)
    ),
    UNIQUE (batch_id),
    UNIQUE (dictionary_edit_id)
);

ALTER TABLE alinhamento.batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE alinhamento.dictionary_edits ENABLE ROW LEVEL SECURITY;
ALTER TABLE alinhamento.sqlite_imports ENABLE ROW LEVEL SECURITY;
-- No policies: only the privileged, server-side Management API role can use
-- these objects. Neither browser users nor authenticated/anonymous JWTs can.

CREATE FUNCTION alinhamento.prepare_batch()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, alinhamento AS $$
BEGIN
    IF jsonb_typeof(NEW.body) IS DISTINCT FROM 'object' THEN
        RAISE EXCEPTION 'Batch body must be a JSON object' USING ERRCODE = '22023';
    END IF;
    IF TG_OP = 'INSERT' THEN
        NEW.request_body_hash := encode(sha256(convert_to((NEW.body - 'id')::text, 'UTF8')), 'hex');
    ELSE
        IF NEW.request_id IS DISTINCT FROM OLD.request_id
           OR NEW.id IS DISTINCT FROM OLD.id
           OR NEW.request_body_hash IS DISTINCT FROM OLD.request_body_hash THEN
            RAISE EXCEPTION 'Batch identity and creation request are immutable' USING ERRCODE = '22023';
        END IF;
        NEW.updated_at := now();
    END IF;
    NEW.body := jsonb_set(NEW.body, '{id}', to_jsonb(NEW.id), true);
    RETURN NEW;
END;
$$;
CREATE TRIGGER prepare_batch BEFORE INSERT OR UPDATE ON alinhamento.batches
FOR EACH ROW EXECUTE FUNCTION alinhamento.prepare_batch();

CREATE FUNCTION alinhamento.prepare_dictionary_edit()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, alinhamento AS $$
BEGIN
    IF jsonb_typeof(NEW.body) IS DISTINCT FROM 'object' THEN
        RAISE EXCEPTION 'Dictionary edit body must be a JSON object' USING ERRCODE = '22023';
    END IF;
    -- body.id is a competency ID, not this table's numeric identity.
    NEW.request_body_hash := encode(sha256(convert_to(NEW.body::text, 'UTF8')), 'hex');
    RETURN NEW;
END;
$$;
CREATE TRIGGER prepare_dictionary_edit BEFORE INSERT ON alinhamento.dictionary_edits
FOR EACH ROW EXECUTE FUNCTION alinhamento.prepare_dictionary_edit();

CREATE FUNCTION alinhamento.create_batch(p_request_id uuid, p_body jsonb)
RETURNS TABLE (id bigint, body jsonb, revision bigint)
LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, alinhamento AS $$
DECLARE saved alinhamento.batches%ROWTYPE;
BEGIN
    IF p_request_id IS NULL OR jsonb_typeof(p_body) IS DISTINCT FROM 'object' THEN
        RAISE EXCEPTION 'Request UUID and object body are required' USING ERRCODE = '22023';
    END IF;
    INSERT INTO alinhamento.batches(request_id, body) VALUES (p_request_id, p_body)
        ON CONFLICT (request_id) DO NOTHING;
    SELECT b.* INTO STRICT saved FROM alinhamento.batches b WHERE b.request_id = p_request_id;
    IF saved.request_body_hash <> encode(sha256(convert_to((p_body - 'id')::text, 'UTF8')), 'hex') THEN
        RAISE EXCEPTION 'Request UUID already belongs to a different batch payload' USING ERRCODE = '23505';
    END IF;
    RETURN QUERY SELECT saved.id, saved.body, saved.revision;
END;
$$;

CREATE FUNCTION alinhamento.create_dictionary_edit(p_request_id uuid, p_body jsonb)
RETURNS TABLE (id bigint, body jsonb)
LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, alinhamento AS $$
