$$;

CREATE FUNCTION alinhamento.import_batch(
    p_source_key text, p_source_id bigint, p_fingerprint text,
    p_request_id uuid, p_body jsonb
)
RETURNS TABLE (id bigint, body jsonb, revision bigint, imported boolean)
LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, alinhamento AS $$
DECLARE
    mapped alinhamento.sqlite_imports%ROWTYPE;
    saved alinhamento.batches%ROWTYPE;
    candidate_body jsonb := p_body;
BEGIN
    IF p_source_key IS NULL OR length(p_source_key) NOT BETWEEN 1 AND 2048
       OR p_source_id IS NULL OR p_source_id < 1
       OR p_fingerprint IS NULL OR p_fingerprint !~ '^[0-9a-f]{64}$'
       OR p_request_id IS NULL OR jsonb_typeof(p_body) IS DISTINCT FROM 'object' THEN
        RAISE EXCEPTION 'Valid source identity, fingerprint, request UUID and object body are required' USING ERRCODE = '22023';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended('alinhamento:batch:' || p_source_key || ':' || p_source_id::text, 0));
    SELECT m.* INTO mapped FROM alinhamento.sqlite_imports m
        WHERE m.source_key = p_source_key AND m.entity_type = 'batch' AND m.source_id = p_source_id;
    IF FOUND THEN
        IF mapped.fingerprint <> p_fingerprint OR mapped.original_body <> p_body THEN
            RAISE EXCEPTION 'Source batch changed after its first import; no data was overwritten' USING ERRCODE = '23505';
        END IF;
        SELECT b.* INTO STRICT saved FROM alinhamento.batches b WHERE b.id = mapped.batch_id;
        RETURN QUERY SELECT saved.id, saved.body, saved.revision, false;
        RETURN;
    END IF;
    -- Serialize allocation with ordinary INSERTs while preserving an unused
    -- source identity. Sequence advancement never moves behind existing rows.
    LOCK TABLE alinhamento.batches IN SHARE ROW EXCLUSIVE MODE;
    IF EXISTS (SELECT 1 FROM alinhamento.batches b WHERE b.request_id = p_request_id) THEN
        RAISE EXCEPTION 'Import request UUID is already in use without this source mapping' USING ERRCODE = '23505';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM alinhamento.batches b WHERE b.id = p_source_id) THEN
        INSERT INTO alinhamento.batches(id, request_id, body)
            VALUES (p_source_id, p_request_id, candidate_body) RETURNING * INTO saved;
    ELSE
        PERFORM setval('alinhamento.batches_id_seq'::regclass,
            greatest((SELECT coalesce(max(b.id), 1) FROM alinhamento.batches b),
                     (SELECT s.last_value FROM alinhamento.batches_id_seq s)), true);
        IF NOT candidate_body ? 'sample_seed' THEN
            candidate_body := jsonb_set(candidate_body, '{sample_seed}', to_jsonb(p_source_id), true);
        END IF;
        INSERT INTO alinhamento.batches(request_id, body)
            VALUES (p_request_id, candidate_body) RETURNING * INTO saved;
    END IF;
    PERFORM setval('alinhamento.batches_id_seq'::regclass,
        greatest(saved.id, (SELECT s.last_value FROM alinhamento.batches_id_seq s)), true);
    INSERT INTO alinhamento.sqlite_imports(source_key, entity_type, source_id, fingerprint, original_body, batch_id)
        VALUES (p_source_key, 'batch', p_source_id, p_fingerprint, p_body, saved.id);
    RETURN QUERY SELECT saved.id, saved.body, saved.revision, true;
END;
$$;

CREATE FUNCTION alinhamento.import_dictionary_edit(
    p_source_key text, p_source_id bigint, p_fingerprint text,
    p_request_id uuid, p_body jsonb
)
RETURNS TABLE (id bigint, body jsonb, imported boolean)
LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, alinhamento AS $$
DECLARE mapped alinhamento.sqlite_imports%ROWTYPE;
        saved alinhamento.dictionary_edits%ROWTYPE;
BEGIN
    IF p_source_key IS NULL OR length(p_source_key) NOT BETWEEN 1 AND 2048
       OR p_source_id IS NULL OR p_source_id < 1
       OR p_fingerprint IS NULL OR p_fingerprint !~ '^[0-9a-f]{64}$'
       OR p_request_id IS NULL OR jsonb_typeof(p_body) IS DISTINCT FROM 'object' THEN
        RAISE EXCEPTION 'Valid source identity, fingerprint, request UUID and object body are required' USING ERRCODE = '22023';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended('alinhamento:dictionary_edit:' || p_source_key || ':' || p_source_id::text, 0));
    SELECT m.* INTO mapped FROM alinhamento.sqlite_imports m
        WHERE m.source_key = p_source_key AND m.entity_type = 'dictionary_edit' AND m.source_id = p_source_id;
    IF FOUND THEN
        IF mapped.fingerprint <> p_fingerprint OR mapped.original_body <> p_body THEN
            RAISE EXCEPTION 'Source dictionary edit changed after its first import; no data was overwritten' USING ERRCODE = '23505';
        END IF;
        SELECT d.* INTO STRICT saved FROM alinhamento.dictionary_edits d WHERE d.id = mapped.dictionary_edit_id;
        RETURN QUERY SELECT saved.id, saved.body, false;
        RETURN;
    END IF;
    LOCK TABLE alinhamento.dictionary_edits IN SHARE ROW EXCLUSIVE MODE;
    IF EXISTS (SELECT 1 FROM alinhamento.dictionary_edits d WHERE d.request_id = p_request_id) THEN
        RAISE EXCEPTION 'Import request UUID is already in use without this source mapping' USING ERRCODE = '23505';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM alinhamento.dictionary_edits d WHERE d.id = p_source_id) THEN
        INSERT INTO alinhamento.dictionary_edits(id, request_id, body)
            VALUES (p_source_id, p_request_id, p_body) RETURNING * INTO saved;
    ELSE
        PERFORM setval('alinhamento.dictionary_edits_id_seq'::regclass,
            greatest((SELECT coalesce(max(d.id), 1) FROM alinhamento.dictionary_edits d),
                     (SELECT s.last_value FROM alinhamento.dictionary_edits_id_seq s)), true);
        INSERT INTO alinhamento.dictionary_edits(request_id, body)
            VALUES (p_request_id, p_body) RETURNING * INTO saved;
    END IF;
    PERFORM setval('alinhamento.dictionary_edits_id_seq'::regclass,
        greatest(saved.id, (SELECT s.last_value FROM alinhamento.dictionary_edits_id_seq s)), true);
    INSERT INTO alinhamento.sqlite_imports(source_key, entity_type, source_id, fingerprint, original_body, dictionary_edit_id)
        VALUES (p_source_key, 'dictionary_edit', p_source_id, p_fingerprint, p_body, saved.id);
    RETURN QUERY SELECT saved.id, saved.body, true;
END;
$$;

-- Array/object guards keep audit views queryable even for historical payloads
-- with missing or differently shaped fields. raw retains every original field.
CREATE VIEW alinhamento.disciplines WITH (security_invoker = true) AS
SELECT b.id AS batch_id, d.ordinality AS position, d.value->>'id' AS discipline_id,
       d.value->>'name' AS name, d.value->'page' AS page, d.value AS raw
FROM alinhamento.batches b CROSS JOIN LATERAL jsonb_array_elements(
    CASE WHEN jsonb_typeof(b.body->'disciplines') = 'array' THEN b.body->'disciplines' ELSE '[]'::jsonb END
) WITH ORDINALITY d(value, ordinality);

CREATE VIEW alinhamento.jobs WITH (security_invoker = true) AS
SELECT b.id AS batch_id, j.ordinality AS position, j.value->>'id' AS job_id,
       j.value->>'title' AS title, j.value->>'company' AS company,
       j.value->>'city' AS city, j.value->>'area' AS area, j.value->'date' AS publication_date,
       j.value->>'source' AS source, j.value AS raw
FROM alinhamento.batches b CROSS JOIN LATERAL jsonb_array_elements(
    CASE WHEN jsonb_typeof(b.body->'jobs') = 'array' THEN b.body->'jobs' ELSE '[]'::jsonb END
) WITH ORDINALITY j(value, ordinality);

CREATE VIEW alinhamento.associations WITH (security_invoker = true) AS
SELECT b.id AS batch_id, a.ordinality AS position, a.value->>'id' AS association_id,
       a.value->>'job_id' AS job_id, a.value->>'discipline_id' AS discipline_id,
       a.value->>'competency_id' AS competency_id, a.value->>'method' AS method,
       a.value->>'verdict' AS verdict, a.value->>'decision' AS decision, a.value AS raw
FROM alinhamento.batches b CROSS JOIN LATERAL jsonb_array_elements(
    CASE WHEN jsonb_typeof(b.body#>'{results,associations}') = 'array' THEN b.body#>'{results,associations}' ELSE '[]'::jsonb END
) WITH ORDINALITY a(value, ordinality);

CREATE VIEW alinhamento.annotations WITH (security_invoker = true) AS
SELECT b.id AS batch_id, a.key AS annotator, label_group.key AS annotation_type,
       label.ordinality AS position, label.value AS raw, a.value AS annotation_document
FROM alinhamento.batches b
CROSS JOIN LATERAL jsonb_each(CASE WHEN jsonb_typeof(b.body->'annotations') = 'object' THEN b.body->'annotations' ELSE '{}'::jsonb END) a
CROSS JOIN LATERAL jsonb_each(CASE WHEN jsonb_typeof(a.value->'labels') = 'object' THEN a.value->'labels' ELSE '{}'::jsonb END) label_group
CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(label_group.value) = 'array' THEN label_group.value ELSE '[]'::jsonb END) WITH ORDINALITY label(value, ordinality);

CREATE VIEW alinhamento.evidence WITH (security_invoker = true) AS
SELECT b.id AS batch_id, 'competency'::text AS owner_type, c.value->>'id' AS owner_id,
       ev.ordinality AS position, ev.value->>'source' AS source,
       ev.value->>'source_id' AS source_id, ev.value->>'text' AS text,
       ev.value->'page' AS page, ev.value->>'section' AS section, ev.value AS raw
FROM alinhamento.batches b
CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(b.body#>'{results,competencies}') = 'array' THEN b.body#>'{results,competencies}' ELSE '[]'::jsonb END) c(value)
CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(c.value->'evidence') = 'array' THEN c.value->'evidence' ELSE '[]'::jsonb END) WITH ORDINALITY ev(value, ordinality)
UNION ALL
SELECT b.id, 'association'::text, a.value->>'id', ev.ordinality,
       ev.value->>'source', ev.value->>'source_id', ev.value->>'text',
       ev.value->'page', ev.value->>'section', ev.value
FROM alinhamento.batches b
CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(b.body#>'{results,associations}') = 'array' THEN b.body#>'{results,associations}' ELSE '[]'::jsonb END) a(value)
CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(a.value->'evidence') = 'array' THEN a.value->'evidence' ELSE '[]'::jsonb END) WITH ORDINALITY ev(value, ordinality)
UNION ALL
SELECT b.id, 'llm_competency'::text, c.value->>'competency_id', c.ordinality,
       c.value->>'source', c.value->>'source_id', c.value->>'text',
       c.value->'page', c.value->>'section', c.value
FROM alinhamento.batches b
CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(b.body#>'{results,llm,competencies}') = 'array' THEN b.body#>'{results,llm,competencies}' ELSE '[]'::jsonb END) WITH ORDINALITY c(value, ordinality);

CREATE VIEW alinhamento.validation WITH (security_invoker = true) AS
SELECT b.id AS batch_id, b.body#>>'{validation,status}' AS status,
       b.body#>>'{results,fingerprint}' AS input_fingerprint, b.body->'validation' AS raw
FROM alinhamento.batches b WHERE b.body ? 'validation';

